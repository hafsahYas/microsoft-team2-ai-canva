// Ollama Cloud integration for AI text generation.
//
// Ollama Cloud runs models remotely and exposes a standard Ollama HTTP API
// at https://ollama.com. See https://docs.ollama.com/cloud for details.
// We call it with the native /api/chat endpoint (non-streaming), so this
// module also works against a local Ollama daemon by setting OLLAMA_HOST.
//
// IMPORTANT: env vars are read lazily inside generateContent() (not at module
// load). ES module imports are hoisted, so this file would otherwise execute
// before dotenv.config() runs in index.ts.

interface ChatMessage {
  role: string;
  content: string;
}

interface ChatResponse {
  model?: string;
  message?: { role?: string; content?: string };
  error?: string;
  /** Input tokens sent to the model (Ollama non-streaming response). */
  prompt_eval_count?: number;
  /** Output tokens generated by the model. */
  eval_count?: number;
}

/** Structured result of a text generation call, including token usage. */
export interface GenerateResult {
  content: string;
  model: string;
  promptTokens: number;
  completionTokens: number;
  totalTokens: number;
}

/**
 * Calls an Ollama model with a system + user prompt and returns the text reply
 * plus token usage.
 *
 * - Endpoint:      POST {OLLAMA_HOST}/api/chat   (default https://ollama.com)
 * - Auth:          Bearer token from OLLAMA_API_KEY (ollama.com API key)
 * - Model:         OLLAMA_MODEL (default "deepseek-v4.1-flash")
 * - Max tokens:    8192 (via options.num_predict)
 */
export async function generateContent(
  systemPrompt: string,
  userPrompt: string
): Promise<GenerateResult> {
  const host = process.env.OLLAMA_HOST || "https://ollama.com";
  const apiKey = process.env.OLLAMA_API_KEY;
  const model = process.env.OLLAMA_MODEL || "deepseek-v4.1-flash";

  const headers: Record<string, string> = { "Content-Type": "application/json" };
  if (apiKey) {
    headers.Authorization = `Bearer ${apiKey}`;
  }

  const messages: ChatMessage[] = [
    { role: "system", content: systemPrompt },
    { role: "user", content: userPrompt },
  ];

  const res = await fetch(`${host}/api/chat`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      model,
      stream: false,
      options: { num_predict: 8192 },
      messages,
    }),
  });

  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new Error(
      `Ollama request failed (${res.status}): ${text.slice(0, 300)}`
    );
  }

  const data = (await res.json()) as ChatResponse;
  const content = data.message?.content;
  if (!content) {
    throw new Error(
      `Ollama returned no content. ${data.error || ""}`.trim()
    );
  }

  const promptTokens = data.prompt_eval_count ?? 0;
  const completionTokens = data.eval_count ?? 0;
  return {
    content,
    model: data.model || model,
    promptTokens,
    completionTokens,
    totalTokens: promptTokens + completionTokens,
  };
}
